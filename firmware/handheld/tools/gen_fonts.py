#!/usr/bin/env python3
"""Generate the handheld's LVGL C fonts from Inter (SIL OFL 1.1).

LVGL's bitmap fonts carry no OpenType features, so tabular figures are baked in
first: the digits' cmap entries are pointed at Inter's `tnum` glyphs (zero.tf
...), every digit then has the same advance, and a changing number does not
jitter. Kerning is left out for the same reason.

Needs: fontTools, node + `npm i lv_font_conv@1.5.3`, Inter 4.x OTFs
(Debian/Ubuntu: fonts-inter).

    python3 tools/gen_fonts.py [--inter DIR] [--conv PATH/lv_font_conv]

The output in main/ui/fonts/ is committed; CI does not run this.
"""
import argparse
import pathlib
import re
import subprocess
import tempfile

from fontTools.ttLib import TTFont

HERE = pathlib.Path(__file__).resolve().parent
OUT = HERE.parent / "main" / "ui" / "fonts"

# ASCII, plus-minus, degree, micro, middle dot, lambda, minus
TEXT = "0x20-0x7E,0xB1,0xB0,0xB5,0xB7,0x3BB,0x2212"
NUM = "0x20,0x2B,0x2D,0x2E,0x30-0x3A"        # space + - . 0-9 :
NUM_FLAG = NUM + ",0x46,0x4E,0x4F"           # ... and F N O for ON / OFF

# name, weight, px, ranges
FONTS = [
    ("hh_font_16", "Bold", 16, TEXT),         # smallest text on the device
    ("hh_font_20", "ExtraBold", 20, TEXT),
    ("hh_font_28", "ExtraBold", 28, TEXT),
    ("hh_num_36", "ExtraBold", 36, NUM_FLAG), # sensor tile values
    ("hh_num_52", "ExtraBold", 52, NUM),      # gauge tile values
    ("hh_num_84", "ExtraBold", 84, NUM),      # GPS speed
]


def bake_tabular(src: pathlib.Path, dst: pathlib.Path) -> None:
    font = TTFont(str(src))
    subst = {}
    gsub = font["GSUB"].table
    for rec in gsub.FeatureList.FeatureRecord:
        if rec.FeatureTag != "tnum":
            continue
        for index in rec.Feature.LookupListIndex:
            for sub in gsub.LookupList.Lookup[index].SubTable:
                sub = getattr(sub, "ExtSubTable", sub)
                subst.update(getattr(sub, "mapping", {}))
    digits = ["zero", "one", "two", "three", "four", "five", "six", "seven", "eight", "nine"]
    missing = [d for d in digits if d not in subst]
    if missing:
        raise SystemExit(f"{src.name}: no tnum glyph for {missing}")
    widths = {font["hmtx"][subst[d]][0] for d in digits}
    if len(widths) != 1:
        raise SystemExit(f"{src.name}: tnum digits are not one width: {widths}")
    for table in font["cmap"].tables:
        if not table.isUnicode():
            continue
        for code, glyph in list(table.cmap.items()):
            if glyph in digits:
                table.cmap[code] = subst[glyph]
    font.save(str(dst))


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--inter", default="/usr/share/fonts/opentype/inter")
    ap.add_argument("--conv", default="lv_font_conv")
    args = ap.parse_args()
    OUT.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory() as tmp:
        baked = {}
        for name, weight, px, ranges in FONTS:
            if weight not in baked:
                baked[weight] = pathlib.Path(tmp) / f"Inter-{weight}-tnum.otf"
                bake_tabular(pathlib.Path(args.inter) / f"Inter-{weight}.otf", baked[weight])
            subprocess.run(
                [args.conv, "--font", str(baked[weight]), "--range", ranges,
                 "--size", str(px), "--bpp", "4", "--format", "lvgl",
                 "--no-compress", "--no-prefilter", "--no-kerning",
                 "--lv-include", "lvgl.h", "--lv-font-name", name,
                 "-o", str(OUT / f"{name}.c")],
                check=True)
            # the converter writes its command line, temp paths included, into the file
            out = OUT / f"{name}.c"
            text = re.sub(r"^ \* Opts: .*$",
                          f" * Source: Inter {weight} (OFL 1.1), tabular digits, ranges {ranges}\n"
                          " * Generated by tools/gen_fonts.py; do not edit.",
                          out.read_text(), count=1, flags=re.M)
            out.write_text(text)
            print(f"{name}: Inter {weight} {px} px")


if __name__ == "__main__":
    main()
